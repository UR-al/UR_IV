# -*- coding: utf-8 -*-
"""Writes ``web/ai_studio/post_schema.js`` from the pack's ``studio_post_schema.py``.

The JS twin of the table: ``export const POST_SCHEMA = ...``. ComfyUI auto-loads every ``.js`` under ``web/``, so it only
exports. ``tests/test_studio_post_schema.py`` checks that this script reproduces the file.

Run: ``venv\\Scripts\\python.exe tools\\build_studio_post_schema.py``
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / "comfy_custom_nodes" / "ai_studio_forge_parity"
TARGET = PACK / "web" / "ai_studio" / "post_schema.js"


def _schema() -> dict:
    spec = importlib.util.spec_from_file_location("studio_post_schema", PACK / "studio_post_schema.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.POST_SCHEMA


def render(schema: dict) -> str:
    body = json.dumps(schema, ensure_ascii=False, indent=1)
    return (
        "// Generated by tools/build_studio_post_schema.py from studio_post_schema.py: do not edit.\n"
        "// No side effects: ComfyUI loads every .js under web/.\n"
        f"export const POST_SCHEMA = Object.freeze({body});\n"
    )


def main() -> None:
    TARGET.write_text(render(_schema()), encoding="utf-8", newline="\n")
    print(TARGET)


if __name__ == "__main__":
    main()
