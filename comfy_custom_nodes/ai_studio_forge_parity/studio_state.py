def _int(value, default, lo, hi, step=1):
    if isinstance(value, bool):
        return default
    try:
        number = int(float(value)) if isinstance(value, str) else int(value)
    except (TypeError, ValueError, OverflowError):
        return default
    number = max(lo, min(hi, number))
    return max(lo, min(hi, (number // step) * step)) if step > 1 else number


def _float(value, default, lo, hi):
    if isinstance(value, bool):
        return default
    try:
        number = float(value)
    except (TypeError, ValueError, OverflowError):
        return default
    if not math.isfinite(number):
        return default
    return max(lo, min(hi, number))


def _str(value, default, allow_empty=True):
    if not isinstance(value, str) or (not allow_empty and not value):
        return default
    return value


def _bool(value, default):
    return value if isinstance(value, bool) else default


def _enum(value, default, key):
    return value if value in _ENUMS[key] else default


def _section(raw, default: dict, fields: dict) -> dict:
    """Normalize one nested dict; ``fields`` maps key -> callable(value, default)."""
    raw = raw if isinstance(raw, dict) else {}
    return {key: fn(raw.get(key), default[key]) for key, fn in fields.items()}


def _lora(item) -> dict | None:
    if not isinstance(item, dict):
        return None
    return {
        "on": _bool(item.get("on"), True),
        "name": _str(item.get("name"), ""),
        "strength": _float(item.get("strength"), 1.0, -10.0, 10.0),
    }


def _ext_field(field: dict, value):
    kind, default = field["kind"], field["default"]
    if kind == "bool":
        return _bool(value, default)
    if kind == "int":
        return _int(value, default, field["min"], field["max"])
    if kind == "float":
        return _float(value, default, field["min"], field["max"])
    if kind == "text":
        return _str(value, default)
    choices = field["choices"]  # empty: a file list of the user's ComfyUI, any name goes
    return value if isinstance(value, str) and (not choices or value in choices) else default


def _post_fields(section: str) -> dict:
    """The ``_section`` entries of one ``POST_SCHEMA`` section."""
    return {field["key"]: (lambda value, _default, field=field: _ext_field(field, value)) for field in POST_SCHEMA[section]}


def _ext(raw) -> dict:
    """Every extension of the table: ``on`` and its fields, coerced and clamped; unknown keys are dropped."""
    raw = raw if isinstance(raw, dict) else {}
    out = {}
    for item in EXT_SCHEMA["extensions"]:
        values = raw.get(item["key"])
        values = values if isinstance(values, dict) else {}
        out[item["key"]] = {"on": _bool(values.get("on"), False),
                            **{field["key"]: _ext_field(field, values.get(field["key"])) for field in item["fields"]}}
    return out


def _family_memory(raw) -> dict:
    """The known families' saved picks, coerced like the top-level keys of the same name."""
    raw = raw if isinstance(raw, dict) else {}
    out = {}
    for slot in MEMORY_SLOTS:
        if isinstance(raw.get(slot), dict):
            out[slot] = _section(raw[slot], DEFAULT_STATE, {
                "te": _str,
                "vae": _str,
                "sampler": lambda v, df: _str(v, df, allow_empty=False),
                "scheduler": lambda v, df: _str(v, df, allow_empty=False),
                "steps": lambda v, df: _int(v, df, 1, 150),
                "cfg": lambda v, df: _float(v, df, 0.0, 30.0),
                "shift": lambda v, df: _float(v, df, 0.0, 100.0),
            })
    return out


def _reference(raw) -> dict:
    raw = raw if isinstance(raw, dict) else {}
    d = DEFAULT_STATE["reference"]
    enum = lambda key: (lambda v, df: _enum(v, df, key))
    guidance = lambda v, df: _float(v, df, 0.0, 20.0)
    unit = lambda v, df: _float(v, df, 0.0, 1.0)
    weight = lambda v, df: _float(v, df, 0.0, 2.0)
    return {
        "on": _bool(raw.get("on"), d["on"]),
        "image": _str(raw.get("image"), d["image"]),
        "image_2": _str(raw.get("image_2"), d["image_2"]),
        "method": _enum(raw.get("method"), d["method"], "method"),
        "megapixels": _float(raw.get("megapixels"), d["megapixels"], 0.25, 2.0),
        "snapref": _section(raw.get("snapref"), d["snapref"], {
            "file": _str,
            "mode": enum("mode"),
            "strength": lambda v, df: _float(v, df, -3.0, 3.0),
            "fidelity": unit,
            "weight_1": weight,
            "weight_2": weight,
            "guidance_on": _bool,
            "guidance": guidance,
            "correction": enum("correction"),
            "ref_end": unit,
            "caption": _str,
        }),
        "ref_adapter": _section(raw.get("ref_adapter"), d["ref_adapter"], {
            "file": _str,
            "strength": lambda v, df: _float(v, df, 0.0, 2.0),
            "guidance": guidance,
            "correction": enum("correction"),
            "ref_end": unit,
        }),
        "krea2": _section(raw.get("krea2"), d["krea2"], {
            "file": _str,
            "strength": lambda v, df: _float(v, df, -10.0, 10.0),
            "grounding_px": lambda v, df: _int(v, df, 0, 4096),
            "boost": lambda v, df: _float(v, df, 0.0, 1000.0),
            "position": enum("position"),
        }),
    }


